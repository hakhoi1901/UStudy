type AcademicDepartmentSeed = {
    id: string;
    parentId: string;
    name: string;
    shortName?: string;
    aliases: string[];
    summary: string;
    areas: string[];
    sourceUrl: string;
};

const academicDepartment = (seed: AcademicDepartmentSeed): CampusUnit => ({
    id: seed.id,
    type: 'department',
    parentId: seed.parentId,
    name: seed.name,
    ...(seed.shortName ? { shortName: seed.shortName } : {}),
    aliases: seed.aliases,
    summary: seed.summary,
    services: [
        {
            id: 'teaching-and-research',
            name: 'Giảng dạy, học thuật và nghiên cứu',
            details: [
                {
                    type: 'list',
                    title: 'Lĩnh vực/hoạt động chính',
                    items: seed.areas,
                },
                {
                    type: 'paragraph',
                    text: 'Sinh viên liên hệ Văn phòng Khoa trước đối với thủ tục học vụ; liên hệ Bộ môn khi cần tư vấn chuyên môn, hướng nghiên cứu, thực tập, khóa luận hoặc nhóm nghiên cứu.',
                },
                { type: 'link', label: 'Xem trang đơn vị', href: seed.sourceUrl },
            ],
        },
    ],
    websites: [seed.sourceUrl],
    locations: [],
    sourceUrl: seed.sourceUrl,
    lastVerifiedAt: '2026-08-15',
    verificationStatus: 'verified',
});

type LaboratorySeed = {
    id: string;
    parentId?: string;
    name: string;
    shortName?: string;
    aliases: string[];
    summary: string;
    capabilities: string[];
    sourceUrl: string;
    phones?: string[];
    emails?: string[];
    websites?: string[];
    locations?: CampusUnit['locations'];
    verificationStatus?: CampusUnit['verificationStatus'];
};

const laboratory = (seed: LaboratorySeed): CampusUnit => ({
    id: seed.id,
    type: 'laboratory',
    ...(seed.parentId ? { parentId: seed.parentId } : {}),
    name: seed.name,
    ...(seed.shortName ? { shortName: seed.shortName } : {}),
    aliases: seed.aliases,
    summary: seed.summary,
    services: [
        {
            id: 'research-and-laboratory-activities',
            name: 'Nghiên cứu và hoạt động phòng thí nghiệm',
            details: [
                { type: 'list', title: 'Năng lực/hướng hoạt động công khai', items: seed.capabilities },
                {
                    type: 'notice',
                    tone: 'info',
                    title: 'Liên hệ trước',
                    text: 'Khả năng tiếp nhận mẫu, sử dụng thiết bị, thực tập hoặc hợp tác phụ thuộc quy trình, an toàn phòng thí nghiệm và kế hoạch chuyên môn tại thời điểm đăng ký.',
                },
                { type: 'link', label: 'Xem nguồn thông tin đơn vị', href: seed.sourceUrl },
            ],
        },
    ],
    ...(seed.phones ? { phones: seed.phones } : {}),
    ...(seed.emails ? { emails: seed.emails } : {}),
    websites: seed.websites ?? [seed.sourceUrl],
    locations: seed.locations ?? [],
    sourceUrl: seed.sourceUrl,
    lastVerifiedAt: '2026-08-15',
    verificationStatus: seed.verificationStatus ?? 'verified',
});

